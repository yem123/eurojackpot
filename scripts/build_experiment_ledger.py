"""
scripts/build_experiment_ledger.py

Reads the actual results/*.json files on disk (never hand-typed) and
produces results/EXPERIMENT_LEDGER.md: an exact, auditable count of every
model, strategy, feature, and statistical test run across the project so
far, plus which steps touched what is now the frozen holdout window.

Usage:
    python scripts/build_experiment_ledger.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from features import FEATURE_SPEC_VERSION, FROZEN_MAIN_FEATURES, FROZEN_EURO_FEATURES  # noqa: E402


def load(path):
    p = ROOT / path
    return json.loads(p.read_text()) if p.exists() else None


def count_significance_tests(sig_json):
    if sig_json is None:
        return 0
    return sum(len(v) for v in sig_json.values())


def main():
    step6_main = load("results/step6/main_results.json")
    step6_euro = load("results/step6/euro_results.json")
    step6_sig = load("results/step6/significance.json")

    step7_main = load("results/step7/main_results.json")
    step7_euro = load("results/step7/euro_results.json")
    step7_sig = load("results/step7/significance.json")

    step8_main = load("results/step8/main_validation_results.json")
    step8_euro = load("results/step8/euro_validation_results.json")
    step8_sig = load("results/step8/significance.json")

    model_spec = load("results/model_spec.json")

    rows = []

    def add_row(step, feature_count_main, feature_count_euro, main_json, euro_json, sig_json, touches_holdout):
        learned = [m for m in (main_json or {}) if m not in ("Historical Frequency", "Recent-N Frequency",
                                                                "Recent-20 Frequency", "Random Expectation")]
        strategies = list((main_json or {}).keys())
        rows.append({
            "step": step,
            "n_models_learned": len(learned),
            "n_strategies_total": len(strategies),
            "n_features_main": feature_count_main,
            "n_features_euro": feature_count_euro,
            "n_significance_tests": count_significance_tests(sig_json),
            "touches_holdout_window": touches_holdout,
            "strategies": strategies,
        })

    add_row("Step 6 — Model Comparison", 1, 1, step6_main, step6_euro, step6_sig,
            touches_holdout=True)  # last-100-draw "test" set == today's holdout window
    add_row("Step 7 — Feature Engineering", len(FROZEN_MAIN_FEATURES), len(FROZEN_EURO_FEATURES),
            step7_main, step7_euro, step7_sig, touches_holdout=True)  # same window, still called "test"
    add_row("Step 8 — Advanced ML (validation only)", len(FROZEN_MAIN_FEATURES), len(FROZEN_EURO_FEATURES),
            step8_main, step8_euro, step8_sig, touches_holdout=False)  # corrected: validation window only

    total_sig_tests = sum(r["n_significance_tests"] for r in rows)
    total_holdout_exposures = sum(r["n_significance_tests"] for r in rows if r["touches_holdout_window"])

    lines = []
    lines.append("# EuroJackpot Project — Experiment Ledger")
    lines.append("")
    lines.append("Auto-generated by `scripts/build_experiment_ledger.py` from the actual result files")
    lines.append("on disk — not hand-maintained. Re-run after any step to refresh.")
    lines.append("")
    lines.append("## Frozen feature spec")
    lines.append("")
    lines.append(f"- **Version:** `{FEATURE_SPEC_VERSION}`")
    lines.append(f"- **Main pool features ({len(FROZEN_MAIN_FEATURES)}):** {', '.join(FROZEN_MAIN_FEATURES)}")
    lines.append(f"- **Euro pool features ({len(FROZEN_EURO_FEATURES)}):** {', '.join(FROZEN_EURO_FEATURES)}")
    lines.append("- Frozen at the end of Step 7. Any change requires bumping the version and")
    lines.append("  re-running Steps 6-7's baseline comparisons (see features.py header comment).")
    lines.append("")
    lines.append("## Per-step summary")
    lines.append("")
    lines.append("| Step | Learned models | Total strategies (incl. baselines) | Main features | Euro features | Significance tests run | Touched today's holdout window? |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in rows:
        lines.append(f"| {r['step']} | {r['n_models_learned']} | {r['n_strategies_total']} | "
                      f"{r['n_features_main']} | {r['n_features_euro']} | {r['n_significance_tests']} | "
                      f"{'**YES**' if r['touches_holdout_window'] else 'No'} |")
    lines.append("")
    lines.append(f"**Total statistical tests run across the project so far: {total_sig_tests}**")
    lines.append(f"**Of which run against what is now the frozen holdout window (draw_idx 590-689): {total_holdout_exposures}**")
    lines.append("")
    lines.append("## Holdout exposure — read this before trusting any p-value on that window")
    lines.append("")
    lines.append("Steps 6 and 7 both evaluated every strategy against 'the last 100 draws' (draw_idx")
    lines.append("590-689), calling it a test set. That is the *same draw range* now designated the")
    lines.append("project's holdout. Across those two steps, it was scored by")
    lines.append(f"**{total_holdout_exposures} separate permutation tests**, never mind the underlying")
    lines.append("avg-hits/log-loss/Brier numbers reported alongside them.")
    lines.append("")
    lines.append("No model was tuned, dropped, or selected based on those numbers — every strategy was")
    lines.append("reported uniformly in both steps, so there was no *model-selection* leakage. But repeated")
    lines.append("exposure like this is still enough that this window can no longer be honestly called an")
    lines.append("untouched final holdout. That is why Step 8 (and everything after it) switched to a")
    lines.append("separate validation window (draw_idx 490-589) for model selection, and why the holdout")
    lines.append("(590-689) has not been scored by anything since. See `src/splits.py` for the full")
    lines.append("rationale and `src/experiment_log.py` for how the eventual one-time holdout run is gated")
    lines.append("behind a frozen model spec.")
    lines.append("")
    lines.append("**Practical takeaway:** treat every Step 6/7 number on the last-100-draws window as")
    lines.append("exploratory/descriptive, not as a valid final significance test. Any p-value quoted from")
    lines.append("Step 6 or 7 should be read informally.")
    lines.append("")
    lines.append("## Current data split (from Step 8 onward)")
    lines.append("")
    lines.append("| Split | Draw range (draw_idx) | Size | Used for |")
    lines.append("|---|---|---|---|")
    lines.append("| Train | 1 - 489 | 489 draws | Fitting every model |")
    lines.append("| Validation | 490 - 589 | 100 draws | Model **selection** (Step 8 onward) |")
    lines.append("| Holdout | 590 - 689 | 100 draws | Reserved. One final evaluation only, after model spec is frozen for a pool. |")
    lines.append("")
    lines.append("## Frozen model spec (from Step 8)")
    lines.append("")
    if model_spec:
        for pool, spec in model_spec.items():
            lines.append(f"- **{pool.title()} pool:** `{spec['selected_model']}` "
                          f"(feature spec `{spec['feature_spec_version']}`) — {spec['selection_notes']}")
    else:
        lines.append("- Not yet frozen (Step 8 has not been run).")
    lines.append("")
    lines.append("The holdout may not be used for either pool until this file exists with `frozen: true`")
    lines.append("for that pool — enforced by `experiment_log.require_frozen_spec()`, not just by convention.")
    lines.append("")

    out_path = ROOT / "results" / "EXPERIMENT_LEDGER.md"
    out_path.write_text("\n".join(lines))
    print(f"Ledger written to {out_path}")
    print(f"Total significance tests so far: {total_sig_tests} ({total_holdout_exposures} against the holdout window)")


if __name__ == "__main__":
    main()
